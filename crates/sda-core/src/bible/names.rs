/// Canonical names for one language.
pub fn names(lang: Language) -> &'static [&'static str; 66] {
    match lang {
        Language::En => &EN,
        Language::It => &IT,
        Language::Ro => &RO,
    }
}

/// Folded lower case aliases, already stripped of dots and accents.
/// Aliases are checked after an exact canonical match and before prefix matching.
